#!/usr/bin/env python3
"""Generate Sources/CodeIslandCore/PetSprites.swift from design/pets.json.

    python3 scripts/gen_pet_sprites.py
    python3 scripts/gen_pet_sprites.py design/v03/candidates.json .build/candidates/PetSprites.swift
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = pathlib.Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT / "design" / "pets.json"
OUT = pathlib.Path(sys.argv[2]).resolve() if len(sys.argv) > 2 else ROOT / "Sources" / "CodeIslandCore" / "PetSprites.swift"


def main() -> None:
    data = json.loads(SRC.read_text())
    species = data["species"]
    lines = [
        "// Generated by scripts/gen_pet_sprites.py from design/pets.json — do not edit.",
        "// 16x16 agent pets; states and animation after anthropics/claude-desktop-buddy (MIT).",
        "",
        "public enum PetSpecies: String, CaseIterable, Sendable {",
    ]
    for key in species:
        lines.append(f"    case {key}")
    lines += ["}", "", "extension PetSpecies {"]

    lines.append("    /// Display name (zh-Hans).")
    lines.append("    public var displayName: String {")
    lines.append("        switch self {")
    for key, sp in species.items():
        lines.append(f'        case .{key}: return "{sp["name"]}"')
    lines += ["        }", "    }", ""]

    lines.append("    public var sprite: PetSprite {")
    lines.append("        switch self {")
    for key, sp in species.items():
        grid = sp["grid"]
        assert len(grid) == 16 and all(len(r) == 16 for r in grid), key
        pal = ", ".join(f'"{c}": 0x{v.lstrip("#").upper()}' for c, v in sp["pal"].items())
        rows = ",\n                ".join(f'"{r}"' for r in grid)
        lines.append(f"        case .{key}:")
        lines.append("            return PetSprite(rows: [")
        lines.append(f"                {rows}")
        face = sp.get("face")
        face_arg = f', screenFace: PetScreenFace(x: {face["x"]}, y: {face["y"]})' if face else ""
        lines.append(f'            ], palette: [{pal}], eyeBackground: "{sp["eyeBg"]}"{face_arg})')
    lines += ["        }", "    }", ""]

    lines.append("    /// Which pet each agent source gets.")
    sources = data.get("sources", {})
    if not sources:
        lines += ["    public static let bySource: [String: PetSpecies] = [:]", ""]
    else:
        lines.append("    public static let bySource: [String: PetSpecies] = [")
        for src, key in sources.items():
            assert key in species, (src, key)
            lines.append(f'        "{src}": .{key},')
        lines += ["    ]", ""]
    if data.get("defaultSpecies"):
        lines.append(f"    public static let fallback: PetSpecies = .{data['defaultSpecies']}")
    elif lines[-1] == "":
        lines.pop()
    lines.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(species)} species, {len(data.get('sources', {}))} sources)")


if __name__ == "__main__":
    main()
